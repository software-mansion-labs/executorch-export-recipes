'''
  Important notes 
  The exported model is fsmn-vad coming from [FUN-ASR](https://huggingface.co/funasr/fsmn-vad).

  in `FUN-ASR` the preprocessing of waveform consists of four phases:
  1. Windowing/Framing (each frame is 25ms, shifted by 10ms)
  2. Convert to log-mel scale by:
    - applying `hamming` window for each frame
    - applying `fft` for each frame
    - using `kaldi.fbank` with 80 mel bank filters
  3. applying `LFR` (low frame rate) preprocessing (stacking 5 next frames to create bigger frame)
  4. applying `CMVN` (cepstral mean and variance normalization) with precomputed weights 

  The original **preprocessing** pipeline might be found in the file `wav_frontend.py` in the `funasr/frontends` directory. Note that the preprocessing uses `FrontendWavOnline` class, not the `FrontendWav` class.

  I have made some small internal changes, but overall preprocessing pipeline is the same. 

  The final exported model takes steps `2-4` inside the model black-box, so here we focus only on the step 1.

  After some tests, I have decided that **postprocessing** from fsmn-vad is unnecessarily compleceted, therefore i have used something similair to what is used in [silero-vad](https://github.com/snakers4/silero-vad/blob/master/src/silero_vad/utils_vad.py). 
'''
