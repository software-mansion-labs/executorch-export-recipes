# numeric_limits<float>::epsilon() 1.1920928955078125e-07
EPSILON = torch.tensor(torch.finfo(torch.float).eps)

def _get_epsilon(device, dtype):
    return EPSILON.to(device=device, dtype=dtype)

def fbank(
    strided_input: torch.Tensor,
    mel_energies: torch.Tensor, 
) -> torch.Tensor:
    device, dtype = strided_input.device, strided_input.dtype 
    spectrum = torch.fft.rfft(strided_input).abs()
    spectrum = spectrum.pow(2.0)
    mel_energies = torch.mm(spectrum, mel_energies.T)
    mel_energies = torch.max(mel_energies, _get_epsilon(device, dtype)).log()
    return mel_energies

def load_cmvn(cmvn_file = "precomputed_data/am.mvn"):
    with open(cmvn_file, "r", encoding="utf-8") as f:
        lines = f.readlines()
    means_list = []
    vars_list = []
    for i in range(len(lines)):
        line_item = lines[i].split()
        if line_item[0] == "<AddShift>":
            line_item = lines[i + 1].split()
            if line_item[0] == "<LearnRateCoef>":
                add_shift_line = line_item[3 : (len(line_item) - 1)]
                means_list = list(add_shift_line)
                continue
        elif line_item[0] == "<Rescale>":
            line_item = lines[i + 1].split()
            if line_item[0] == "<LearnRateCoef>":
                rescale_line = line_item[3 : (len(line_item) - 1)]
                vars_list = list(rescale_line)
                continue
    means = np.array(means_list).astype(np.float32)
    vars = np.array(vars_list).astype(np.float32)
    cmvn = np.array([means, vars])
    cmvn = torch.as_tensor(cmvn, dtype=torch.float32)
    return cmvn

'''
  As an input VAD takes:
    strided_input: A tensor of audio frames,  generated by applying a
                   25ms window with a 10ms hop/stride to the raw waveform.
  Vad Returns:
    scores: A tensor with shape (1, num_frames, num_classes=247).
            - 'num_frames' corresponds to the total number of time steps, where each
              step represents a 10ms interval.
            - The last dimension contains the class probabilities for each frame.
            
            Specifically, 'scores[0, t, 0]' holds the probability that speech is
            *NOT* present in the frame centered at time t * 10ms.
            We ignore all classes other than this.

  This VAD class is standard FSMN VAD class but it includes parts of utilities,
  that are preprocessing. specifically it adds to the class:
    1. conversion to log-mel scale with 80 mel bank filters. The mel-filter matrix 
    is same as computed by kaldi fbank.
    2. applying low frame rate. In this case it simply stacks next 5 frames with       sizes  80 to create new single frame  with size 400. 
    3. applying cepstral mean and variance normalization with weights precomputed and hardcoded into the FSMN-VAD preprocessing.  

'''
class VAD(FSMN):
  def __init__(self, input_dim, input_affine_dim, fsmn_layers, linear_dim, proj_dim, lorder, rorder, lstride, rstride, output_affine_dim, output_dim, use_softmax = True):

    super().__init__(input_dim, input_affine_dim, fsmn_layers, linear_dim, proj_dim, lorder, rorder, lstride, rstride, output_affine_dim, output_dim, use_softmax)
    self.cmvn = load_cmvn()
    self.LFR_M=5
    self.WINDOW = "hamming"
    self.N_MELS = 80 
    self.FRAME_LEN = 25 
    self.FRAME_LENGTH_MS = 25
    self.FRAME_STEP_MS = 10    
    self.SAMPLE_RATE = 16000
    self.mel_energies = torch.load("precomputed_data/mel_energies_tensor.pt")


  def my_fbank(self, waveform : torch.tensor):
    waveform = waveform * (1 << 15)
    mat = fbank(waveform, self.mel_energies )
    return mat 
  
  def apply_lfr(self, features: torch.Tensor) -> torch.Tensor:
    T, D = features.shape
    context_size = (self.LFR_M - 1) // 2

    features_3d = features.unsqueeze(0)
    
    padded_3d = nn.functional.pad(
        features_3d, (0, 0, context_size, context_size), mode='replicate'
    )
    
    output_size = (1, T, self.LFR_M * D)
    output_stride = (padded_3d.stride()[0], D, 1)
    lfr_view = padded_3d.as_strided(output_size, output_stride)

    return lfr_view.clone()

  def apply_cmvn(self, inputs: torch.Tensor) -> torch.Tensor:
    dim = inputs.shape[-1]
    means = self.cmvn[0:1, :dim]
    variances = self.cmvn[1:2, :dim]
    inputs = inputs + means
    inputs = inputs * variances
    return inputs.type(torch.float32)
  
  def preprocess(self, input: torch.Tensor) -> torch.Tensor:
    feats = self.my_fbank(input)
    feats = self.apply_lfr(feats)
    feats = self.apply_cmvn(feats)  
    return feats 
  
  def forward(self,input: torch.Tensor) -> torch.Tensor: 
    x = self.preprocess(input)
    return super().forward(x) 
